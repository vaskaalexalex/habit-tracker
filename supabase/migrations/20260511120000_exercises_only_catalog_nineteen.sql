-- Новые строки только каталог (user_id должен быть null); иначе снова появятся «лишние» упражнения
create or replace function public.exercises_reject_non_catalog_rows()
returns trigger
language plpgsql
as $$
begin
  if new.user_id is not null then
    raise exception 'catalog_only: только 19 упражнений каталога, пользовательские строки запрещены';
  end if;
  return new;
end;
$$;

drop trigger if exists exercises_reject_non_catalog_insert on public.exercises;

create trigger exercises_reject_non_catalog_insert
before insert on public.exercises
for each row
execute function public.exercises_reject_non_catalog_rows();
