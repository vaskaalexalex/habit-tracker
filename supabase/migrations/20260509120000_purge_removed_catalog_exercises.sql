        'скотта',
        'разгибания на блоке',
        'разгибания над головой',
        'тяга штанги к подбородку',
        'махи назад в наклоне',
        'боковая планка',
        'велосипед',
        'подъём ног в висе',
        'русские скручивания',
        'жим на гантелей плечи'
      )
    );

  delete from public.workout_sets ws
  using purge_exercises p
  where ws.exercise_id = p.id;

  delete from public.exercises e
  using purge_exercises p
  where e.id = p.id;
end $$;
