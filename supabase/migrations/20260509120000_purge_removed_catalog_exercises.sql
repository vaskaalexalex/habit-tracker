    '11111111-1111-4111-8111-111111010034'::uuid,
    '11111111-1111-4111-8111-111111010035'::uuid,
    '11111111-1111-4111-8111-111111010036'::uuid,
    '11111111-1111-4111-8111-111111010037'::uuid
  ];
begin
  create temp table purge_exercises on commit drop as
  select e.id
  from public.exercises e
  where e.id != all (catalog)
    and (
      (e.is_preset and e.user_id is null)
      or lower(trim(e.name)) in (
        -- retired names (historical seeds minus final catalog); typos
        'жим лёжа',
        'жим под углом',
        'разводка гантелей',
        'приседания со штангой',
        'жим ногами',
        'румынская тяга',
        'выпады с гантелями',
        'становая тяга',
        'тяга штанги в наклоне',
        'армейский жим',
        'подъём штанги на бицепс',
        'молотки',
        'отжимания на брусьях',
        'скручивания',
        'планка',
        'сведения в кроссовере',
        'отжимания',
        'тяга гантели одной рукой',
        'гиперэкстензия',
        'шраги',
        'подтягивания обратным хватом',
